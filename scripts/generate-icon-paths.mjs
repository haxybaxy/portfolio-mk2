// Extracts the SVG path of each Simple Icons glyph the site uses into src/data/simpleIconPaths.ts,
// so the app ships ~50 path strings instead of the whole icon library. Run with `npm run icons`.
import { readFileSync, writeFileSync } from 'node:fs'

const SLUGS = [
  'astro', 'buffer', 'c', 'cmake', 'cplusplus', 'digitalocean', 'django', 'docker', 'dotnet', 'expo', 'express',
  'fastapi', 'firebase', 'flutter', 'git', 'go', 'lua', 'githubactions', 'gnubash', 'googleanalytics', 'googlecloud', 'html5',
  'huggingface', 'javascript', 'langchain', 'langgraph', 'linux', 'mongodb', 'mysql', 'nestjs', 'nextdotjs',
  'nodedotjs', 'nvidia', 'opencv', 'pandas', 'postgresql', 'python', 'pytorch', 'railway', 'raspberrypi', 'react',
  'ros', 'scikitlearn', 'sqlite', 'supabase', 'tensorflow', 'terraform', 'typescript', 'vite', 'webgpu',
]

const pkg = new URL('../node_modules/simple-icons/', import.meta.url)
const { version } = JSON.parse(readFileSync(new URL('package.json', pkg), 'utf8'))

const entries = SLUGS.map((slug) => {
  const svg = readFileSync(new URL(`icons/${slug}.svg`, pkg), 'utf8')
  const path = /<path d="([^"]+)"/.exec(svg)?.[1]
  if (!path) throw new Error(`simple-icons: no path found for "${slug}"`)
  return `  ${slug}: '${path}',`
})

const out = `// Generated by scripts/generate-icon-paths.mjs from simple-icons ${version}. Do not edit; run \`npm run icons\`.
// Icons are CC0; trademarks belong to their owners. 24x24 viewBox.
export const SIMPLE_ICON_PATHS = {
${entries.join('\n')}
} as const
`
writeFileSync(new URL('../src/data/simpleIconPaths.ts', import.meta.url), out)
console.log(`wrote ${SLUGS.length} icon paths from simple-icons ${version}`)
